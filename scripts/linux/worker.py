def finalize_pipeline_state(state: dict, requested_stages: list[str]) -> dict:
    """Seal native Linux state with the shared per-stage/public outcome contract."""
    records = state.setdefault("stages", {})
    canonical: dict[str, dict] = {}
    upstream: dict | None = None
    for name in requested_stages:
        raw = records.get(name)
        if raw is None:
            inherited = upstream or exit_contract.stage_outcome(
                status=exit_contract.STAGE_ERROR,
                outcome_class=exit_contract.OUTCOME_INFRA_ERROR,
                reason_code="stage_result_missing",
            )
            raw = exit_contract.stage_outcome(
                status=exit_contract.STAGE_NOT_RUN,
                outcome_class=inherited["outcome_class"],
                reason_code="upstream_stage_failed",
            )
            records[name] = raw
        status = raw.get("status", exit_contract.STAGE_ERROR)
        try:
            item = exit_contract.validate_stage_outcome(raw)
        except ValueError:
            item = exit_contract.outcome_from_stage_status(status, raw=raw)
        canonical[name] = item
        if item["status"] != exit_contract.STAGE_PASS and upstream is None:
            upstream = item
    state["stage_outcomes"] = canonical
    aggregate = exit_contract.aggregate_stage_outcomes(canonical, requested_stages)
    state.update(aggregate)
    state["pipeline_exit"] = aggregate["process_exit_code"]
    return state


def run_pipeline(
    client,
    task: dict,
    instance_id: str,
    model: str,
    image: str,
    api_key: str,
    base_url: str,
    auth_token: str,
    mcp_provider: str,
    vlm_key: str,
    stage: str = "recreation_eval",
    agent_cli: str = "claude",
    eval_target: str = "recreation",
    vlm_model: str = "",
    vlm_base_url: str = "",
):
    tid = task["task_id"]
    base = vm_task_dir(tid)
    local_base = STATE_DIR / tid
    local_base.mkdir(parents=True, exist_ok=True)

    stages_to_run = list(stages_for(stage))
    state_file = local_base / "pipeline_state.json"

    def finish(current: dict) -> dict:
        current = finalize_pipeline_state(current, stages_to_run)
        state_file.write_text(json.dumps(current, indent=2))
        return current

    try:
        _sync_code_to_vm(client, instance_id)
    except Exception as exc:
        failed_stage = stages_to_run[0]
        state = {
            "task_id": tid,
            "instance_id": instance_id,
            "model": model,
            "stages": {
                failed_stage: {
                    **exit_contract.stage_outcome(
                        status=exit_contract.STAGE_ERROR,
                        outcome_class=exit_contract.OUTCOME_INFRA_ERROR,
                        reason_code="rb_code_sync_failed",
                    ),
                    "time": _now(),
                    "error": "rb_code_sync_failed",
                }
            },
        }
        print(f"ERROR: failed to sync isolated RB code to Linux VM: {exc}")
        return finish(state)

    if stage == "setup":
        # No priors and no artifact restore: setup establishes the boundary and exits.
        print("\n--- SETUP ---")
        setup_result = run_setup(client, task, instance_id, model)
        # run_pipeline's contract is a state dict, and main() reads
        # state["stages"][<stage>]["status"] to decide the exit code. Returning a bare bool here
        # would make `.get("stages", {})` raise on a plain False, or silently pass on True.
        state = {
            "task_id": tid,
            "instance_id": instance_id,
            "model": model,
            "stages": {"setup": {**setup_result, "time": _now()}},
        }
        # And the deployment platform controller does not read this RETURN value -- it reads the state FILE, which the
        # normal path writes as it goes. Skipping it once reported a fully attested
        # boundary (all 8 checks green, SETUP OK) and still fail the job with "Unexpected exit code 0",
        # because required_stages=["setup"] found nothing on disk to match.
        local_base.mkdir(parents=True, exist_ok=True)
        return finish(state)

    print(f"\n{'=' * 60}")
    print(f"Pipeline: {tid}")
    vm_label = instance_id[-8:] if instance_id else "<unset>"
    print(f"Target: {vm_label}  Model: {model}  MCP: {mcp_provider}")
    print(f"Stages: {' → '.join(stages_to_run)}")
    print(f"{'=' * 60}")

    # Ensure base dir exists
    run_command(client, f"mkdir -p {base}", instance_id=instance_id, timeout=15)
    time.sleep(2)

    if state_file.exists():
        try:
            state = json.loads(state_file.read_text())
        except json.JSONDecodeError:
            state = {}
    else:
        state = {}
    if state.get("model") != model:
        state = {}
    state["task_id"] = tid
    state["instance_id"] = instance_id
    state["model"] = model
    state.setdefault("stages", {})
    state_file.write_text(json.dumps(state, indent=2))

    # Bootstrap: install packages and start GUI environment on first run
    if not vm_bootstrap.run(
        client,
        instance_id,
        sudo_password=os.environ.get("RB_SSH_PASSWORD", ""),
    ):
        state["stages"][stages_to_run[0]] = {
            **exit_contract.stage_outcome(
                status=exit_contract.STAGE_ERROR,
                outcome_class=exit_contract.OUTCOME_INFRA_ERROR,
                reason_code="bootstrap_failed",
            ),
            "time": time.strftime("%H:%M:%S"),
            "error": "bootstrap_failed",
        }
        return finish(state)

    # The frozen release instance is required input, not output of hidden authoring stages.
    frozen_transport = ("RB_UNIFIED_PREFIX",)
    missing_transport = [name for name in frozen_transport if not os.environ.get(name)]
    if missing_transport:
        state["stages"][stages_to_run[0]] = {
            **exit_contract.stage_outcome(
                status=exit_contract.STAGE_ERROR,
                outcome_class=exit_contract.OUTCOME_INFRA_ERROR,
                reason_code="unified_instance_transport_config_missing",
            ),
            "time": _now(),
            "error": "missing: " + ", ".join(missing_transport),
        }
        return finish(state)
    print("\n--- RESTORE UNIFIED INSTANCE from artifact store ---", flush=True)
    if not _restore_unified_instance(client, instance_id, tid, base):
        state["stages"][stages_to_run[0]] = {
            **exit_contract.stage_outcome(
                status=exit_contract.STAGE_FAIL,
                outcome_class=exit_contract.OUTCOME_DATA_ERROR,
                reason_code="invalid_or_missing_frozen_instance",
                native_exit_code=exit_contract.RC_DATA,
            ),
            "time": _now(),
            "error": "unified_instance_restore_failed",
        }
        return finish(state)
    if stages_to_run[0] == "eval":
        # A full recreation run builds the frozen reference before the agent starts.
        # Besides producing the trusted reference binary, those recipes install
        # app-specific system packages and populate package-manager caches.  Standalone
        # eval must reproduce that same pre-candidate environment before rebuilding a
        # restored candidate; otherwise an identical candidate can launch in the full
        # run and fail only in eval-only because the reference prerequisites are absent.
        print("\n--- MATERIALIZE REFERENCE BUILD ENVIRONMENT ---", flush=True)
        if not prepare_reference_eval_candidate(
            client,
            task,
            instance_id,
            image,
            model,
            api_key,
            base_url,
            auth_token,
            mcp_provider,
            agent_cli=agent_cli,
        ):
            reference_is_target = eval_target == "reference"
            state["stages"]["eval"] = {
                **exit_contract.stage_outcome(
                    status=(
                        exit_contract.STAGE_FAIL
                        if reference_is_target
                        else exit_contract.STAGE_ERROR
                    ),
                    outcome_class=(
                        exit_contract.OUTCOME_DATA_ERROR
                        if reference_is_target
                        else exit_contract.OUTCOME_INFRA_ERROR
                    ),
                    reason_code=(
                        "reference_candidate_build_failed"
                        if reference_is_target
                        else "reference_environment_build_failed"
                    ),
                    native_exit_code=(
                        exit_contract.RC_DATA if reference_is_target else None
                    ),
                ),
                "time": _now(),
                "error": (
                    "reference_candidate_build_failed"
                    if reference_is_target
                    else "reference_environment_build_failed"
                ),
            }
            return finish(state)

    if stages_to_run[0] == "eval" and eval_target == "recreation":
        vm_dir = _stage_vm_dir(base, "recreation", model)
        print("\n--- RESTORE CANDIDATE RECREATION from artifacts ---", flush=True)
        if not _artifact_restore_prefix():
            state["stages"]["eval"] = {
                **exit_contract.stage_outcome(
                    status=exit_contract.STAGE_ERROR,
                    outcome_class=exit_contract.OUTCOME_INFRA_ERROR,
                    reason_code="candidate_transport_config_missing",
                ),
                "time": _now(),
            }
            return finish(state)
        if not _restore_recreation_from_artifacts(client, instance_id, tid, vm_dir):
            state["stages"]["eval"] = {
                **exit_contract.stage_outcome(
                    status=exit_contract.STAGE_FAIL,
                    outcome_class=exit_contract.OUTCOME_DATA_ERROR,
                    reason_code="candidate_recreation_missing",
                    native_exit_code=exit_contract.RC_DATA,
                ),
                "time": _now(),
                "error": "candidate_recreation_restore_failed",
            }
            return finish(state)
        state["stages"]["recreation"] = {
            **exit_contract.stage_outcome(
                status=exit_contract.STAGE_PASS,
                outcome_class=exit_contract.OUTCOME_COMPLETED,
                reason_code="restored_prerequisite",
            ),
            "time": _now(),
            "restored": True,
        }
        state_file.write_text(json.dumps(state, indent=2))
    for stage in stages_to_run:
        print(f"\n--- {stage.upper()} ---")
        stage_result = exit_contract.stage_outcome(
            status=exit_contract.STAGE_ERROR,
            outcome_class=exit_contract.OUTCOME_INFRA_ERROR,
            reason_code="stage_not_started",
        )

        if stage == "recreation":
            stage_result = run_recreation(
                client,
                task,
                instance_id,
                image,
                model,
                api_key,
                base_url,
                auth_token,
                mcp_provider,
                agent_cli=agent_cli,
            )
        elif stage == "eval":
            stage_result = run_eval(
                client,
                task,
                instance_id,
                image,
                model,
                vlm_key,
                eval_target=eval_target,
                vlm_model=vlm_model,
                vlm_base_url=vlm_base_url,
            )

        # Verify
        stage_ran = stage_result["status"] == exit_contract.STAGE_PASS
        verified = (
            verify_stage(
                client,
                task,
                stage,
                instance_id,
                model,
                image,
                eval_target=eval_target,
            )
            if stage_ran
            else False
        )
        if stage_ran and not verified:
            stage_result = exit_contract.stage_outcome(
                status=(
                    exit_contract.STAGE_FAIL
                    if stage == "recreation"
                    else exit_contract.STAGE_ERROR
                ),
                outcome_class=(
                    exit_contract.OUTCOME_COMPLETED
                    if stage == "recreation"
                    else exit_contract.OUTCOME_INFRA_ERROR
                ),
                reason_code=(
                    "no_usable_artifact"
                    if stage == "recreation"
                    else "eval_result_invalid"
                ),
                native_exit_code=stage_result.get("native_exit_code"),
            )
        state["stages"][stage] = {
            **stage_result,
            "time": time.strftime("%H:%M:%S"),
        }

        # A release stage is not complete until its artifacts are present in the pod's
        # $OUTPUT_DIR tree. VM→pod always uses the shared Paramiko/SFTP transport; the store is a
        # subsequent publication target, never a substitute for the local artifact.
        print(f"  Downloading {stage} results through SFTP...", flush=True)
        artifacts_downloaded = False
        try:
            artifacts_downloaded = bool(
                download_stage(
                    client,
                    tid,
                    stage,
                    model,
                    local_base,
                    eval_target=eval_target,
                )
            )
        except Exception as exc:
            print(f"  WARN: failed to download {stage} artifacts: {exc}")
        stage_dir = local_base / stage
        if artifacts_downloaded and stage_dir.is_dir():
            _upload_stage_artifacts(stage_dir, tid, stage)
        elif stage_result["status"] == exit_contract.STAGE_PASS:
            stage_result = exit_contract.stage_outcome(
                status=exit_contract.STAGE_ERROR,
                outcome_class=exit_contract.OUTCOME_INFRA_ERROR,
                reason_code="artifact_sftp_download_failed",
                native_exit_code=stage_result.get("native_exit_code"),
            )
            state["stages"][stage] = {
                **stage_result,
                "time": time.strftime("%H:%M:%S"),
                "error": "artifact_sftp_download_failed",
            }

        # Save state after each stage
        state_file.write_text(json.dumps(state, indent=2))

        if not stage_ran or not verified or not artifacts_downloaded:
            reason = (
                stage_result["reason_code"]
                if not stage_ran
                else (
                    "verification failed"
                    if not verified
                    else "artifact SFTP download failed"
                )
            )
            print(f"\n  ABORT: {stage} {reason}. Resume with --stage {stage}")
            return finish(state)

    print(f"\n{'=' * 60}")
    print(f"COMPLETE: {tid}")
    for s, info in state["stages"].items():
        print(f"  {s}: {info['status']}")
    print(f"{'=' * 60}")
    return finish(state)


def show_status():
    """Show status of all pipeline runs."""
    if not STATE_DIR.exists():
        print("No pipeline results found")
        return
    for task_dir in sorted(STATE_DIR.iterdir()):
        state_file = task_dir / "pipeline_state.json"
        if not state_file.exists():
            continue
        state = json.loads(state_file.read_text())
        tid = state.get("task_id", task_dir.name)
        stages = state.get("stages", {})
        summary = " ".join(f"{s}={info['status']}" for s, info in stages.items())
        print(f"  {tid}: {summary}")


