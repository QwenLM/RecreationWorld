def main():
    parser = argparse.ArgumentParser(description="Recreation-Bench release pipeline")
    parser.add_argument("--tasks", help="Path to tasks.jsonl")
    parser.add_argument(
        "--task-id",
        help="Single frozen-suite task ID",
    )
    parser.add_argument("--instance-id", help="VM instance ID")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--model-base-url", help="Anthropic-compatible model base URL")
    parser.add_argument("--model-api-key", help="Model API key")
    parser.add_argument("--auth-token", help="Anthropic auth token")
    parser.add_argument("--vlm-key", help="VLM judge API key")
    parser.add_argument("--vlm-model", default=os.environ.get("VLM_MODEL", ""))
    parser.add_argument("--vlm-base-url", default=os.environ.get("VLM_BASE_URL", ""))
    parser.add_argument("--image", default=os.environ.get("DOCKER_IMAGE", ""))
    parser.add_argument("--ssh-host", help="SSH backend host")
    parser.add_argument("--ssh-user", default=os.environ.get("RB_SSH_USER", "user"))
    parser.add_argument("--ssh-password", default=os.environ.get("RB_SSH_PASSWORD", ""))
    parser.add_argument(
        "--ssh-port", type=int, default=int(os.environ.get("RB_SSH_PORT", "22"))
    )
    parser.add_argument("--ssh-key-path", default=os.environ.get("RB_SSH_KEY_PATH", ""))
    parser.add_argument(
        "--stage",
        choices=STAGE_VALUES,
        default="recreation_eval",
        help="Lifecycle selection; recreation_eval runs recreation→eval.",
    )
    parser.add_argument(
        "--eval-target",
        choices=EVAL_TARGETS,
        default=os.environ.get("RB_EVAL_TARGET", "recreation"),
        help="Candidate for eval-only runs: recreation or frozen reference",
    )
    parser.add_argument(
        "--mcp-provider",
        choices=["computer-use-mcp", "cua-driver"],
        default="cua-driver",
    )
    parser.add_argument(
        "--agent-cli",
        choices=["claude", "codex", "codex-mcp"],
        default="claude",
        help=(
            "Agent CLI: claude (Claude Code) or codex (OpenAI Codex); all Codex spellings "
            "use the desktop-control MCP server (codex-mcp is a compatibility alias)"
        ),
    )
    parser.add_argument(
        "--download-only",
        action="store_true",
        help="Only download results (no execution)",
    )
    parser.add_argument("--status", action="store_true", help="Show pipeline status")
    args = parser.parse_args()

    if args.status:
        show_status()
        return 0

    load_env()
    # SSH is the only transport, so these are exported unconditionally. They used to be gated on
    # `--backend ssh`, which meant --ssh-host alone silently did nothing.
    if args.ssh_host:
        os.environ["RB_SSH_HOST"] = args.ssh_host
    os.environ["RB_SSH_USER"] = args.ssh_user
    os.environ["RB_SSH_PASSWORD"] = args.ssh_password
    os.environ["RB_SSH_PORT"] = str(args.ssh_port)
    os.environ["RB_SSH_KEY_PATH"] = args.ssh_key_path
    client = get_vm_client()

    # Build task list (needed for both execution and download modes)
    all_tasks = {}
    if args.tasks:
        for line in Path(args.tasks).read_text().splitlines():
            if line.strip():
                t = json.loads(line)
                all_tasks[t["task_id"]] = t

    if args.task_id:
        if args.task_id in all_tasks:
            tasks = [all_tasks[args.task_id]]
        else:
            tasks = [{"task_id": args.task_id}]
    elif args.tasks:
        tasks = list(all_tasks.values())
    else:
        sys.exit("Provide --tasks or --task-id")

    # Download-only mode (no model auth needed)
    if args.download_only:
        for task in tasks:
            instance_id = _require_host(args)
            local_base = STATE_DIR / task["task_id"]
            print(f"\nDownloading: {task['task_id']}")
            for stage in RELEASE_STAGES:
                download_stage(client, task["task_id"], stage, args.model, local_base)
        return 0

    # Setup and eval-only never execute an agent, so model credentials/proxy are
    # irrelevant. The VLM judge has its own credential below.
    if "recreation" not in stages_for(args.stage):
        api_key = args.model_api_key or os.environ.get("MODEL_API_KEY", "")
        auth_token = args.auth_token or os.environ.get("ANTHROPIC_AUTH_TOKEN", "")
        base_url = (
            args.model_base_url
            or os.environ.get("MODEL_BASE_URL")
            or os.environ.get("ANTHROPIC_BASE_URL", "")
        )
    # Auth setup for model-executing stages. Provider selection and translation belong to
    # the deployment layer; the worker receives one explicit endpoint contract.
    else:
        api_key = args.model_api_key or os.environ.get("MODEL_API_KEY", "")
        auth_token = args.auth_token or os.environ.get("ANTHROPIC_AUTH_TOKEN", "")
        base_url = (
            args.model_base_url
            or os.environ.get("MODEL_BASE_URL")
            or os.environ.get("ANTHROPIC_BASE_URL", "")
        )
        if not base_url:
            sys.exit("--model-base-url or MODEL_BASE_URL is required for recreation")
        if not api_key and not auth_token:
            sys.exit(
                "--model-api-key, MODEL_API_KEY, or ANTHROPIC_AUTH_TOKEN is required"
            )

    vlm_key = (
        os.environ.get("VLM_API_KEY")
        or args.vlm_key
        or args.model_api_key
        or os.environ.get("MODEL_API_KEY", "")
    )
    image = args.image or os.environ.get("DOCKER_IMAGE", "")

    # Run pipeline for each task
    expected_stages = stages_for(args.stage)
    outcomes = []
    for i, task in enumerate(tasks):
        instance_id = _require_host(args)
        if len(tasks) > 1:
            _clean_vm_between_tasks(client, task, instance_id)
        state = run_pipeline(
            client,
            task,
            instance_id,
            args.model,
            image,
            api_key,
            base_url,
            auth_token,
            args.mcp_provider,
            vlm_key,
            stage=args.stage,
            agent_cli=args.agent_cli,
            eval_target=args.eval_target,
            vlm_model=args.vlm_model,
            vlm_base_url=args.vlm_base_url,
        )
        outcomes.append(
            exit_contract.aggregate_stage_outcomes(
                state["stage_outcomes"], expected_stages
            )
        )
    if any(
        item["outcome_class"] == exit_contract.OUTCOME_TERMINATED for item in outcomes
    ):
        return exit_contract.RC_TIMEOUT
    if any(
        item["outcome_class"] == exit_contract.OUTCOME_INFRA_ERROR for item in outcomes
    ):
        return exit_contract.RC_INFRA
    if any(
        item["outcome_class"] == exit_contract.OUTCOME_DATA_ERROR for item in outcomes
    ):
        return exit_contract.RC_DATA
    return exit_contract.RC_OK


if __name__ == "__main__":
    raise SystemExit(main())
