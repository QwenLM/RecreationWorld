def _artifact_prefix() -> str:
    return os.environ.get("RB_ARTIFACT_PREFIX", "").rstrip("/")


def _artifact_restore_prefix() -> str:
    return (
        os.environ.get("RB_ARTIFACT_RESTORE_PREFIX", "") or _artifact_prefix()
    ).rstrip("/")


def _upload_stage_artifacts(
    local_dir: Path,
    task_id: str,
    stage: str,
    *,
    store=None,
    prefix: str = "",
) -> bool:
    """Upload a complete stage directory through the configured artifact store."""
    prefix = (prefix or _artifact_prefix()).rstrip("/")
    if not prefix:
        return False
    try:
        store = store or artifact_store_from_environment(os.environ)
        artifact_prefix = f"{prefix}/{task_id}/{stage}/"
        result = upload_tree(store, local_dir, artifact_prefix)
        for relative, exc in result.failures:
            print(f"  WARN: artifact upload failed {relative}: {exc}", flush=True)
        if result.transferred:
            print(
                f"  Uploaded {result.transferred} files -> {artifact_prefix}",
                flush=True,
            )
        return result.complete
    except (ArtifactStoreConfigurationError, ImportError) as exc:
        print(
            f"  WARN: artifact backend unavailable, skipping upload: {exc}", flush=True
        )
    except Exception as exc:
        print(f"  WARN: artifact upload failed: {exc}", flush=True)
    return False


def _upload_stage_from_vm(
    client,
    instance_id: str,
    task_id: str,
    stage: str,
    remote_sources: list[tuple[str, str]],
) -> bool:
    """Checkpoint VM directories through the deployment platform worker into the canonical key layout.

    Each source is ``(remote_directory, relative_destination)``.  This matters while
    Linux recreation is still running: the live authoring tree and stream-json output
    are deliberately kept outside the protected, task-named stage directory and only
    copied there after the agent exits.  A checkpoint of that stage directory therefore
    contains no in-progress work.

    The sandbox VM cannot be assumed to have network access to the configured artifact
    store even when the controller can reach it. Download over the existing SSH/SFTP
    control channel first, then let the controller perform the artifact upload.
    """
    prefix = _artifact_prefix()
    if not prefix:
        raise RuntimeError("candidate recreation artifact prefix is missing")
    try:
        store = artifact_store_from_environment(os.environ)
    except (ArtifactStoreConfigurationError, ImportError) as exc:
        raise RuntimeError(
            f"candidate recreation artifact store unavailable: {exc}"
        ) from exc

    with tempfile.TemporaryDirectory(prefix="rb_linux_checkpoint_") as tmp:
        checkpoint_root = Path(tmp)
        downloaded = 0
        for remote_dir, relative_destination in remote_sources:
            local_dir = checkpoint_root / relative_destination.strip("/")
            try:
                downloaded += client.download_dir(
                    remote_dir,
                    str(local_dir),
                    DOWNLOAD_EXCLUDES,
                )
            except Exception as exc:
                print(
                    f"  WARN: checkpoint download failed {remote_dir}: {exc}",
                    flush=True,
                )
        if downloaded == 0:
            return False
        return _upload_stage_artifacts(
            checkpoint_root,
            task_id,
            stage,
            store=store,
            prefix=prefix,
        )


def _restore_unified_instance(client, instance_id: str, app_id: str, base: str) -> bool:
    """Download, validate, and deploy one frozen release instance.

    The canonical on-VM layout stays canonical: ``reference/`` and ``tests/`` are
    never renamed to historical stage directories. Missing or malformed components
    fail closed; there is no authoring or per-stage artifact fallback.
    """
    unified_prefix = os.environ.get("RB_UNIFIED_PREFIX", "").strip()
    if not unified_prefix:
        return False
    platform = os.environ.get("RB_UNIFIED_PLATFORM", "ubuntu")
    try:
        store = artifact_store_from_environment(os.environ)
    except (ArtifactStoreConfigurationError, ImportError) as exc:
        print(f"  frozen instance: artifact store unavailable: {exc}", flush=True)
        return False

    common_dir = Path(__file__).resolve().parents[1] / "common"
    if str(common_dir) not in sys.path:
        sys.path.insert(0, str(common_dir))
    from rb_unify.eval_bridge import download_unified, manifest_from_instance
    from rb_unify.rb_instance import RBInstance

    with tempfile.TemporaryDirectory(prefix="rb_frozen_linux_") as tmp:
        rep = download_unified(
            unified_prefix,
            platform,
            app_id,
            tmp,
            components=("reference", "tests"),
            override=os.environ.get("RB_UNIFIED_APP", ""),
            store=store,
        )
        if not rep.get("prefix"):
            return False
        instance = RBInstance.load(tmp)
        problems = [str(p) for p in instance.validate() if p.component != "vlm"]
        if problems or instance.platform != "ubuntu":
            print(
                "  invalid frozen instance: "
                + "; ".join(problems or [f"platform={instance.platform!r}"]),
                flush=True,
            )
            return False

        manifest_path = instance.tests_dir / "test_manifest.json"
        if not manifest_path.is_file():
            print(
                "  invalid frozen instance: tests/test_manifest.json missing",
                flush=True,
            )
            return False
        manifest_changed = False
        try:
            manifest = json.loads(manifest_path.read_text())
            if instance.vlm_path.is_file():
                vlm = manifest_from_instance(tmp)
                manifest["vlm_assertions"] = vlm["vlm_assertions"]
                manifest["vlm_total"] = len(vlm["vlm_assertions"])
                manifest_changed = True
        except (json.JSONDecodeError, AttributeError, KeyError, TypeError) as exc:
            print(f"  invalid frozen instance manifest: {exc}", flush=True)
            return False
        if manifest_changed:
            manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False))

        client.run(
            f"rm -rf {shlex.quote(base)}/reference {shlex.quote(base)}/tests "
            f"{shlex.quote(base)}/instance.json {shlex.quote(base)}/vlm_assertions.json; "
            f"mkdir -p {shlex.quote(base)}/reference {shlex.quote(base)}/tests",
            timeout=60,
        )
        client.upload_dir(str(instance.reference_dir), f"{base}/reference")
        client.upload_dir(str(instance.tests_dir), f"{base}/tests")
        client.upload_file(str(Path(tmp) / "instance.json"), f"{base}/instance.json")
        if instance.vlm_path.is_file():
            client.upload_file(str(instance.vlm_path), f"{base}/vlm_assertions.json")

    print(f"  frozen instance ready: {rep['prefix']}", flush=True)
    return True


def _restore_recreation_from_artifacts(
    client, instance_id: str, task_id: str, vm_stage_dir: str
) -> bool:
    """Carry the candidate recreation from VM1 to a fresh eval VM.

    This is release output continuity, not an alternate source for frozen reference
    or tests. Those always come from the unified instance.
    """
    prefix = _artifact_restore_prefix()
    if not prefix:
        return False
    artifact_prefix = f"{prefix}/{task_id}/recreation/"

    try:
        store = artifact_store_from_environment(os.environ)
    except (ArtifactStoreConfigurationError, ImportError) as exc:
        raise RuntimeError(
            f"candidate recreation artifact store unavailable: {exc}"
        ) from exc

    # ``prepare_reference_eval_candidate`` runs the trusted build as root before
    # this restore.  recreation.run() uses the same run-owned stage directory for
    # its control files, so that directory can contain root-owned files after the
    # reference-only phase.  Restore into a clean directory owned by the SSH
    # principal instead of attempting to overwrite those files.  Besides fixing
    # the permission boundary, this guarantees that a standalone eval grades the
    # immutable candidate exactly, without mixing in helper files from the
    # reference build that preceded it.
    quoted_target = shlex.quote(vm_stage_dir)
    try:
        with tempfile.TemporaryDirectory(prefix="rb_linux_restore_") as tmp:
            result = download_tree(
                store,
                artifact_prefix,
                tmp,
                executable=lambda relative: relative.endswith(".sh"),
            )
            if result.transferred == 0:
                return False

            invoke_id = run_command(
                client,
                (
                    f"sudo -n rm -rf -- {quoted_target} && "
                    f"install -d -m 0700 -- {quoted_target}"
                ),
                instance_id=instance_id,
                timeout=300,
            )
            cleanup = _wait_quick_result(client, invoke_id, max_wait=300)
            if not cleanup or cleanup.get("status") != "Success":
                detail = (
                    cleanup.get("output", "") if cleanup else "missing command result"
                )
                raise RuntimeError(
                    f"candidate recreation target cleanup failed: {detail}"
                )
            client.upload_dir(tmp, vm_stage_dir)
            count = result.transferred
    except RuntimeError:
        raise
    except Exception as exc:
        raise RuntimeError(
            f"candidate recreation artifact restore failed: {exc}"
        ) from exc
    print(
        f"  Restored {count} files from artifact prefix {artifact_prefix}",
        flush=True,
    )
    return True


