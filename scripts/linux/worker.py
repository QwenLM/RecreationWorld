#!/usr/bin/env python3
"""Native Linux VM worker for the Recreation-Bench release lifecycle.

Each stage runs through one command client over SSH in a controller-provisioned
deployment platform sandbox VM (or an explicit bring-your-own host).
Runs are resumable by selecting the stage to run with ``--stage``.

Usage:
    # Full pipeline for one task
    python scripts/linux/worker.py \
        --task-id pencil2d-pencil \
        --instance-id <instance-id>

    # Run only the recreation stage
    python scripts/linux/worker.py \
        --task-id pencil2d-pencil \
        --instance-id <instance-id> --stage recreation

    # Download existing results without running stages
    python scripts/linux/worker.py \
        --task-id pencil2d-pencil \
        --instance-id <instance-id> --download-only

    # Check status of a running pipeline
    python scripts/linux/worker.py --status
"""

