def verify_stage(
    client,
    task: dict,
    stage: str,
    instance_id: str,
    model: str,
    image: str,
    eval_target: str = "recreation",
) -> bool:
    """Verify stage outputs exist on VM. Returns True if valid."""
    task_id = task["task_id"]
    base = vm_task_dir(task_id)

    if stage == "recreation":
        rec = _rec_dir(base, model)
        out = _vm_check(
            client,
            instance_id,
            _python_runtime_command("recreation_status.py", "verify", rec),
        )
        try:
            data = _last_json_line(out)
        except json.JSONDecodeError:
            print(f"  Recreation verify: FAIL (could not parse: {out})")
            return False
        ok = bool(data.get("ok"))
        print(
            f"  Recreation verify: {'PASS' if ok else 'FAIL'} "
            f"(build.sh={data.get('has_build')}, launch.sh={data.get('has_launch')}, "
            f"src_files={data.get('src_count')}, "
            f"bash_syntax={data.get('bash_syntax')}, "
            f"launch_syntax={data.get('launch_syntax')}, "
            f"forbidden_command={data.get('forbidden_command')}, "
            f"reference_path={data.get('references_workspace_reference')}, "
            f"blocked_commands={data.get('blocked_commands')})"
        )
        return ok

    elif stage == "eval":
        rec_variant = _eval_variant(model, eval_target)
        eval_dir = f"{base}/atspi_eval_{rec_variant}"
        out = _vm_check(
            client,
            instance_id,
            _python_runtime_command("eval_results.py", "verify", eval_dir),
        )
        try:
            data = _last_json_line(out)
        except json.JSONDecodeError:
            print(f"  Eval verify: FAIL (could not parse results: {out})")
            return False
        if not data.get("ok"):
            missing = ", ".join(data.get("missing", []))
            print(f"  Eval verify: FAIL (missing/invalid results: {missing or data})")
            return False
        prog = data["programmatic"]
        vlm = data["vlm"]
        if int(prog["total"]) <= 0:
            print(f"  Eval verify: FAIL (total={prog['total']}, no tests ran)")
            return False
        if prog.get("error"):
            print(f"  Eval verify: FAIL (programmatic_error={prog['error']})")
            return False
        not_run = int(prog.get("n_not_run", prog.get("n_injected_not_run", 0)))
        if not_run >= int(prog["total"]):
            print(
                "  Eval verify: FAIL "
                f"(executed=0/{prog['total']}, every test is not_run)"
            )
            return False
        if vlm.get("error"):
            print(f"  Eval verify: FAIL (vlm_error={vlm['error']})")
            return False
        manifest_note = ""
        if prog.get("scored_against") == "manifest":
            manifest_note = (
                f" [manifest {str(prog.get('manifest_sha', ''))[:8]} "
                f"denom={prog['total']} injected={prog.get('n_injected_not_run', 0)} "
                f"unexpected={prog.get('n_unexpected', 0)}]"
            )
        print(
            "  Eval verify: PASS "
            f"(programmatic: {prog['passed']}/{prog['total']} = "
            f"{prog['pass_rate']:.1%}{manifest_note}; "
            f"vlm: {vlm['passed']}/{vlm['total']} = {vlm['pass_rate']:.1%}"
            f"{', skipped=' + vlm['skipped'] if vlm.get('skipped') else ''})"
        )
        return True

    return False


