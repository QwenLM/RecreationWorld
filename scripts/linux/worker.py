def _sync_code_to_vm(client, instance_id: str) -> None:
    """Copy the complete RB tree into a root-only directory in the Linux guest.

    Linux now consumes the same in-guest shared helpers as Windows/macOS.  The
    controller code is preparation input, never agent context, so this transfer
    fails closed unless root can read it and the configured agent principal cannot.
    """

    repo_root = Path(__file__).resolve().parents[2]
    agent_user = os.environ.get("RB_LINUX_AGENT_USER", "user")
    remote_archive = f"/tmp/rb_code_{os.getpid()}.tar.gz"
    with tempfile.TemporaryDirectory(prefix="rb_linux_code_") as tmp:
        local_archive = Path(tmp) / "recreationbench.tar.gz"
        command = ["tar", "czf", str(local_archive)]
        command.extend(f"--exclude={pattern}" for pattern in CODE_SYNC_EXCLUDES)
        command.extend(["-C", str(repo_root), "."])
        subprocess.run(command, check=True)
        size_mb = local_archive.stat().st_size / (1024 * 1024)
        print(f"  syncing complete RB code to VM ({size_mb:.1f} MiB)", flush=True)
        client.upload_file(str(local_archive), remote_archive)

    script = runtime_assets.render_text(
        "linux/runtime/sync_code_to_vm.sh",
        {
            "__REMOTE_ARCHIVE__": shlex.quote(remote_archive),
            "__VM_CODE_DIR__": shlex.quote(VM_CODE_DIR),
            "__AGENT_USER__": shlex.quote(agent_user),
        },
    )
    result = client.run(
        script,
        timeout=300,
        check=False,
        stdin_text=os.environ.get("RB_SSH_PASSWORD", "") + "\n",
    )
    if result.stdout.strip():
        print(result.stdout.strip(), flush=True)
    if result.stderr.strip():
        print(result.stderr.strip(), file=sys.stderr, flush=True)
    if result.rc:
        raise RuntimeError(f"RB code sync failed with exit code {result.rc}")


def _wait(
    client,
    invoke_id: str,
    stage_name: str,
    poll_interval: int = 30,
    max_wait: int = 14400,
    checkpoint_fn=None,
    checkpoint_every: int = 30,
) -> dict | None:
    """Poll until RunCommand completes, streaming new output lines.

    checkpoint_fn: optional best-effort callable invoked every ``checkpoint_every``
    polls to snapshot the in-progress stage output to the artifact store. Lets a long
    stage survive a mid-run pod/VM loss with a recent partial checkpoint instead of
    losing everything.
    Exceptions are swallowed so a failed checkpoint never aborts the poll.
    """
    print(f"  InvokeId: {invoke_id}", flush=True)
    max_polls = max_wait // poll_interval + 10
    seen = 0
    for i in range(max_polls):
        time.sleep(poll_interval)
        elapsed = (i + 1) * poll_interval
        try:
            result = check_invocation(client, invoke_id)
        except Exception as e:
            print(f"  [{elapsed // 60}m] API error: {str(e)[:80]}", flush=True)
            continue
        output = (result or {}).get("output", "")
        if len(output) > seen:
            for line in output[seen:].rstrip("\n").split("\n"):
                print(f"  [{stage_name}] {line}", flush=True)
            seen = len(output)
        if result and result["status"] in ("Success", "Failed", "Timeout"):
            print(f"  {stage_name}: {result['status']} ({elapsed // 60}m)", flush=True)
            return result
        if checkpoint_fn is not None and i > 0 and i % checkpoint_every == 0:
            try:
                # The return value is the whole point: _upload_stage_from_vm returns False
                # (no exception) when artifact config is absent or the uploader fails.
                # for a checkpoint that uploaded nothing. A successful-looking log is
                # insufficient when the task prefix contains no objects from this run.
                ok = checkpoint_fn()
                if ok is False:
                    print(
                        f"  [{elapsed // 60}m] checkpoint: NOTHING uploaded for "
                        f"{stage_name} (credentials/prefix missing or VM uploader failed)",
                        flush=True,
                    )
                else:
                    print(
                        f"  [{elapsed // 60}m] checkpoint: snapshotted in-progress "
                        f"{stage_name} to the artifact store",
                        flush=True,
                    )
            except Exception as e:
                print(
                    f"  [{elapsed // 60}m] checkpoint failed (non-fatal): {str(e)[:80]}",
                    flush=True,
                )
        if i % 5 == 0 and len(output) <= seen:
            status = result.get("status", "?") if result else "?"
            print(f"  [{elapsed // 60}m] {status}", flush=True)
    print(f"  WARNING: {stage_name} polling timed out", flush=True)
    return None


def _vm_check(
    client,
    instance_id: str,
    cmd: str,
    timeout: int = 30,
    max_wait: float = 15.0,
) -> str:
    """Run a quick command on the selected Linux target and return output."""
    invoke_id = run_command(client, cmd, instance_id=instance_id, timeout=timeout)
    result = _wait_quick_result(client, invoke_id, max_wait=max_wait)
    return (result or {}).get("output", "").strip()


def _wait_quick_result(client, invoke_id: str, max_wait: float = 15.0) -> dict | None:
    """Poll a short RunCommand without the long stage polling cadence."""
    deadline = time.time() + max_wait
    while time.time() < deadline:
        result = check_invocation(client, invoke_id)
        if result and result["status"] in ("Success", "Failed", "Timeout"):
            return result
        time.sleep(0.5)
    return check_invocation(client, invoke_id)


def _now() -> str:
    return time.strftime("%H:%M:%S")


def _rec_dir(base: str, model: str) -> str:
    return f"{base}/recreation_{model.replace('.', '-')}"


def _eval_variant(model: str, eval_target: str = "recreation") -> str:
    if eval_target == "reference":
        return "reference"
    return f"recreation_{model.replace('.', '-')}"


def _stage_vm_dir(
    base: str, stage: str, model: str = "", eval_target: str = "recreation"
) -> str:
    if stage == "setup":
        # It writes its report under /tmp on the VM, not into the task tree, so that establishing
        # the boundary does not itself create a directory inside a protected root.
        return "/tmp/rb_permission"
    elif stage == "recreation":
        return _rec_dir(base, model)
    elif stage == "eval":
        rec_variant = _eval_variant(model, eval_target)
        return f"{base}/atspi_eval_{rec_variant}"
    raise ValueError(f"Unknown stage: {stage}")


def run_setup(client, task: dict, instance_id: str, model: str) -> dict:
    """Establish and attest the agent's file boundary. Launches no agent.

    Fails the stage when the boundary cannot be established OR when the probes disagree with the
    attestation, because a run at an isolation level nobody verified is worse than no run.
    """
    from stages import setup as setup_stage

    # The agent identity and its override now live in core.permission_probe.PLATFORMS /
    # RB_LINUX_AGENT_USER, so this caller only passes what it owns: the client and the task.
    ok, transcript = setup_stage.run(client, instance_id, task["task_id"], model)
    print(transcript[-6000:] if transcript else "(no output from the VM)")
    summary = setup_stage.summarize(transcript)
    print(
        f"  setup: attested={summary['attested']} denied={summary['denied']} "
        f"skipped={summary['skipped']} leaks={summary['leaks']}"
    )
    return exit_contract.stage_outcome(
        status=(exit_contract.STAGE_PASS if ok else exit_contract.STAGE_ERROR),
        outcome_class=(
            exit_contract.OUTCOME_COMPLETED if ok else exit_contract.OUTCOME_INFRA_ERROR
        ),
        reason_code="completed" if ok else "boundary_not_attested",
    )


def _last_json_line(output: str) -> dict:
    """Parse the last JSON object printed by a VM helper script."""
    for line in reversed(output.strip().splitlines()):
        line = line.strip()
        if line.startswith("{") and line.endswith("}"):
            return json.loads(line)
    raise json.JSONDecodeError("no JSON object found", output, 0)


