def _clean_vm_between_tasks(client, task: dict, instance_id: str) -> None:
    """Clean VM state between tasks when running multiple on one VM.

    vm_task_dir() returns a fixed path (/home/user/rb_pipeline/task) to avoid
    leaking app names to the recreation agent. When running multiple tasks
    sequentially, we must clear this shared directory and kill stale processes.
    """
    base = vm_task_dir(task["task_id"])
    cleanup = runtime_assets.render_text(
        "linux/runtime/cleanup_between_tasks.sh", {"__TASK_DIR__": base}
    )
    run_command(client, cleanup, instance_id=instance_id, timeout=60)
    time.sleep(3)


def run_recreation(
    client,
    task,
    instance_id,
    image,
    model,
    api_key,
    base_url,
    auth_token,
    mcp_provider,
    agent_cli="claude",
):
    base = vm_task_dir(task["task_id"])
    rec = _rec_dir(base, model)

    out = _vm_check(
        client,
        instance_id,
        _python_runtime_command("recreation_status.py", "complete", rec),
    )
    if "DONE" in out:
        print("  Recreation already complete, skipping")
        return exit_contract.stage_outcome(
            status=exit_contract.STAGE_PASS,
            outcome_class=exit_contract.OUTCOME_COMPLETED,
            reason_code="already_completed",
        )

    # Agent budget defaults to 20h; raised by RB_RECREATION_AGENT_TIMEOUT or the
    # recreation_timeout param (RECREATION_TIMEOUT) when it exceeds 20h. The outer RunCommand
    # wall must exceed it by ~90m (VM setup + post-run harvest/upload) and must never be
    # clipped by a smaller RECREATION_TIMEOUT, else the agent is severed mid-work.
    agent_budget = max(
        _env_int("RB_RECREATION_AGENT_TIMEOUT", 72000),
        _env_int("RECREATION_TIMEOUT", 0),
    )
    rec_timeout = max(_env_int("RECREATION_TIMEOUT", 72000), agent_budget + 5400)
    invoke_id = recreation.run(
        client,
        task,
        instance_id,
        model,
        image,
        api_key,
        base_url,
        auth_token,
        mcp_provider=mcp_provider,
        timeout=rec_timeout,
        agent_cli=agent_cli,
    )
    result = _wait(
        client,
        invoke_id,
        "Recreation",
        max_wait=rec_timeout + 600,
        # Incremental artifact checkpoint: snapshot the in-progress
        # recreation dir every ~15min so a mid-run pod/VM loss (SSH drop, eviction)
        # leaves a recent partial instead of forfeiting hours of authoring.
        checkpoint_fn=lambda: _upload_stage_from_vm(
            client,
            instance_id,
            task["task_id"],
            "recreation",
            [
                ("/workspace/output", ""),
                ("/workspace/recreation", "recreation"),
            ],
        ),
        checkpoint_every=_env_int("RB_RECREATION_CHECKPOINT_POLLS", 30),
    )
    if not result or result["status"] != "Success":
        print("  RECREATION FAILED")
        native_exit = result.get("exit_code") if result else None
        if native_exit == exit_contract.RC_DATA:
            # The stage script reserves 1 for a valid agent run whose output did
            # not satisfy the recreation artifact contract.
            outcome = exit_contract.OUTCOME_COMPLETED
            reason = "no_usable_artifact"
            status = exit_contract.STAGE_FAIL
        elif (
            exit_contract.from_native_exit(native_exit)
            == exit_contract.OUTCOME_TERMINATED
        ):
            outcome = exit_contract.OUTCOME_TERMINATED
            reason = "worker_terminated"
            status = exit_contract.STAGE_TIMEOUT
        else:
            outcome = exit_contract.OUTCOME_INFRA_ERROR
            reason = "recreation_runner_failed"
            status = exit_contract.STAGE_ERROR
        return exit_contract.stage_outcome(
            status=status,
            outcome_class=outcome,
            reason_code=reason,
            native_exit_code=native_exit,
        )
    return exit_contract.stage_outcome(
        status=exit_contract.STAGE_PASS,
        outcome_class=exit_contract.OUTCOME_COMPLETED,
        reason_code="agent_completed",
        native_exit_code=result.get("exit_code"),
    )


def _env_int(name: str, default: int) -> int:
    try:
        return int(os.environ.get(name, default))
    except (TypeError, ValueError):
        return default


def _vlm_phase_timeout(assertion_count: int) -> int:
    if assertion_count <= 0:
        return _env_int("RB_VLM_NO_ASSERTIONS_TIMEOUT", 600)
    base = _env_int("RB_VLM_BASE_TIMEOUT", 300)
    per_assertion = _env_int("RB_VLM_SECONDS_PER_ASSERTION", 120)
    minimum = _env_int("RB_VLM_MIN_TIMEOUT", 1800)
    maximum = _env_int("RB_VLM_MAX_TIMEOUT", 14400)
    return max(minimum, min(maximum, base + assertion_count * per_assertion))


def prepare_reference_eval_candidate(
    client,
    task,
    instance_id,
    image,
    model,
    api_key,
    base_url,
    auth_token,
    mcp_provider,
    agent_cli="claude",
):
    """Materialize the frozen reference without launching a recreation agent."""
    invoke_id = recreation.run(
        client,
        task,
        instance_id,
        model,
        image,
        api_key,
        base_url,
        auth_token,
        mcp_provider=mcp_provider,
        timeout=5400,
        agent_cli=agent_cli,
        reference_build_only=True,
    )
    result = _wait(client, invoke_id, "Reference candidate build", max_wait=6000)
    if not result or result["status"] != "Success":
        print("  REFERENCE CANDIDATE BUILD FAILED")
        return False
    return True


def run_eval(
    client,
    task,
    instance_id,
    image,
    model,
    vlm_key,
    eval_target="recreation",
    vlm_model="",
    vlm_base_url="",
):
    base = vm_task_dir(task["task_id"])
    rec_variant = _eval_variant(model, eval_target)
    eval_dir = f"{base}/atspi_eval_{rec_variant}"

    out = _vm_check(
        client,
        instance_id,
        _python_runtime_command("eval_results.py", "complete", eval_dir),
    )
    if "DONE" in out:
        print("  Eval already complete, skipping")
        return exit_contract.stage_outcome(
            status=exit_contract.STAGE_PASS,
            outcome_class=exit_contract.OUTCOME_COMPLETED,
            reason_code="already_completed",
        )

    result_ids = atspi_eval.run(
        client,
        task,
        instance_id,
        image,
        variant=rec_variant,
        rec_dir=_rec_dir(base, model),
        candidate_dir="/workspace/install" if eval_target == "reference" else "",
        # The candidate binary is discovered after its frozen, deterministic
        # build. Do not depend on historical reference/build_result.json metadata.
        app_name="",
        vlm_key=vlm_key,
        vlm_model=vlm_model,
        vlm_base_url=vlm_base_url,
    )
    phase1_result = _wait(
        client,
        result_ids["phase1_invoke"],
        "Eval Phase 1",
        max_wait=int(result_ids.get("phase1_timeout", 2400)),
    )
    if not phase1_result or phase1_result["status"] != "Success":
        print("  EVAL PHASE 1 FAILED")
        native_exit = phase1_result.get("exit_code") if phase1_result else None
        # Phase 1 deliberately writes a small marker before returning RC_DATA when
        # the candidate has no runnable artifact. That is an authoritative model
        # zero, not a broken judge: the agent completed and the evaluator proved
        # that there was nothing it could launch. Treating every non-zero phase-1
        # exit as infrastructure would mark these jobs retryable and cause pointless
        # full-agent retries.
        marker = {}
        if native_exit == exit_contract.RC_DATA:
            marker_dir = shlex.quote(result_ids["results_dir"])
            marker_raw = _vm_check(
                client,
                instance_id,
                f"if [ -s {marker_dir}/atspi_eval.json ]; then "
                f"cat {marker_dir}/atspi_eval.json; "
                f"elif [ -s {marker_dir}/programmatic_results.json ]; then "
                f"cat {marker_dir}/programmatic_results.json; fi",
            )
            try:
                marker = _last_json_line(marker_raw)
            except json.JSONDecodeError:
                marker = {}
        if str(marker.get("error") or "") in {
            "no_binary",
            "no_launch_script",
            "no_display",
            "candidate_build_failed",
            "app_launch_failed",
        }:
            return exit_contract.stage_outcome(
                status=exit_contract.STAGE_FAIL,
                outcome_class=exit_contract.OUTCOME_COMPLETED,
                reason_code="no_usable_artifact",
                native_exit_code=native_exit,
            )
        return exit_contract.stage_outcome(
            status=(
                exit_contract.STAGE_TIMEOUT
                if exit_contract.from_native_exit(native_exit)
                == exit_contract.OUTCOME_TERMINATED
                else exit_contract.STAGE_ERROR
            ),
            outcome_class=(
                exit_contract.OUTCOME_TERMINATED
                if exit_contract.from_native_exit(native_exit)
                == exit_contract.OUTCOME_TERMINATED
                else exit_contract.OUTCOME_INFRA_ERROR
            ),
            reason_code=(
                "worker_terminated"
                if exit_contract.from_native_exit(native_exit)
                == exit_contract.OUTCOME_TERMINATED
                else "eval_programmatic_failed"
            ),
            native_exit_code=native_exit,
        )

    assertions_out = _vm_check(
        client,
        instance_id,
        _python_runtime_command(
            "eval_results.py",
            "assertion-count",
            f"{result_ids['results_dir']}/screenshots/assertions.json",
        ),
    )
    try:
        assertion_count = int(assertions_out.strip().splitlines()[-1])
    except (IndexError, ValueError):
        assertion_count = 0
    phase2_timeout = _vlm_phase_timeout(assertion_count)
    print(
        f"  Eval Phase 2 timeout: {phase2_timeout}s "
        f"for {assertion_count} assertions"
    )
    invoke_id = atspi_eval.run_vlm_phase(
        client, instance_id, result_ids["results_dir"], timeout=phase2_timeout
    )
    phase2_result = _wait(
        client, invoke_id, "Eval Phase 2 (VLM)", max_wait=phase2_timeout + 240
    )
    if not phase2_result or phase2_result["status"] != "Success":
        print("  EVAL PHASE 2 FAILED")
        native_exit = phase2_result.get("exit_code") if phase2_result else None
        return exit_contract.stage_outcome(
            status=(
                exit_contract.STAGE_TIMEOUT
                if exit_contract.from_native_exit(native_exit)
                == exit_contract.OUTCOME_TERMINATED
                else exit_contract.STAGE_ERROR
            ),
            outcome_class=(
                exit_contract.OUTCOME_TERMINATED
                if exit_contract.from_native_exit(native_exit)
                == exit_contract.OUTCOME_TERMINATED
                else exit_contract.OUTCOME_INFRA_ERROR
            ),
            reason_code=(
                "worker_terminated"
                if exit_contract.from_native_exit(native_exit)
                == exit_contract.OUTCOME_TERMINATED
                else "eval_vlm_failed"
            ),
            native_exit_code=native_exit,
        )

    return exit_contract.stage_outcome(
        status=exit_contract.STAGE_PASS,
        outcome_class=exit_contract.OUTCOME_COMPLETED,
        reason_code="eval_completed",
        native_exit_code=phase2_result.get("exit_code"),
    )


