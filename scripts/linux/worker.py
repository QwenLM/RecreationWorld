def _python_runtime_command(name: str, *args: str) -> str:
    """Run a controller helper from the root-only RB tree on the VM.

    ``sync_code_to_vm.sh`` deliberately makes ``VM_CODE_DIR`` unreadable to the
    recreation user.  The SSH control process is not guaranteed to run as root,
    so every later controller-side helper invocation must cross that boundary
    explicitly.  Bootstrap installs passwordless sudo for the SSH user before
    these commands can run.
    """

    helper = f"{VM_CODE_DIR}/scripts/linux/runtime/{name}"
    return shlex.join(("sudo", "-n", "--", "python3", helper, *args))


def _require_host(args) -> str:
    """The VM to drive. There used to be a hardcoded 3-instance ECS pool as a fallback, and the
    multi-task loop round-robined across it; with one SSH host per run, fan-out is the caller's job
    (deployment platform already works that way). Failing loudly beats silently driving the wrong machine.
    """
    host = args.instance_id or args.ssh_host or os.environ.get("RB_SSH_HOST", "")
    if not host:
        sys.exit("No VM host. Pass --ssh-host (or --instance-id), or set RB_SSH_HOST.")
    return host


