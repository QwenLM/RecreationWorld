SCORE_FILES = (
    "programmatic_results.json",
    "vlm_results.json",
    "vlm_results.partial.json",
    "atspi_eval.json",
)


def _download_score_files_only(
    client, remote_dir: str, local_dir: Path, stage: str
) -> int:
    """Retry missing score files individually through the same SFTP transport."""
    local_dir.mkdir(parents=True, exist_ok=True)
    saved = []
    for name in SCORE_FILES:
        local = local_dir / name
        if local.is_file():
            continue
        remote = f"{remote_dir}/{name}"
        try:
            client.download_file(remote, str(local))
        except FileNotFoundError:
            continue
        except Exception as exc:
            print(f"    [score retry] {name}: {exc}")
            continue
        try:
            json.loads(local.read_text())
        except (OSError, ValueError):
            local.unlink(missing_ok=True)
            print(f"    [score retry] {name}: not valid JSON, skipped")
            continue
        saved.append(name)
    if saved:
        print(f"    [score retry] recovered {', '.join(saved)} for {stage}")
    return len(saved)


def download_stage(
    client,
    task_id: str,
    stage: str,
    model: str,
    local_base: Path,
    eval_target: str = "recreation",
):
    """Download one complete stage directory directly through Paramiko/SFTP."""
    base = vm_task_dir(task_id)
    remote_dir = _stage_vm_dir(base, stage, model, eval_target)
    local_dir = local_base / stage

    staging = local_base / f".{stage}.sftp"
    if staging.exists():
        shutil.rmtree(staging)
    downloaded = client.download_dir(
        remote_dir, str(staging), exclude_patterns=DOWNLOAD_EXCLUDES
    )
    if stage == "eval":
        downloaded += _download_score_files_only(client, remote_dir, staging, stage)
    if not downloaded:
        shutil.rmtree(staging, ignore_errors=True)
        print(f"  {stage}: SFTP returned no result files")
        return 0

    if local_dir.exists():
        shutil.rmtree(local_dir)
    staging.replace(local_dir)
    file_count = sum(1 for path in local_dir.rglob("*") if path.is_file())
    print(f"  {stage}: downloaded {file_count} files through SFTP to {local_dir}")
    return file_count


